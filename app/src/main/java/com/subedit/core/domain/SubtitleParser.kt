package com.subedit.core.domain

/**
 * Parser dan Serializer penuh untuk file subtitle `.ass` (SubStation Alpha v4+) dan `.srt` (SubRip)
 * dengan dukungan penuh round-trip Aegisub Desktop (23 kolom `[V4+ Styles]`, `[Aegisub Project Garbage]`,
 * `[Aegisub Extradata]`, `[Fonts]`, `[Graphics]`, dan baris `Comment:`).
 */
object SubtitleParser {

    private val KNOWN_SCRIPT_INFO_PREFIXES = listOf(
        "title:",
        "scripttype:",
        "wrapstyle:",
        "scaledborderandshadow:",
        "ycbcr matrix:",
        "playresx:",
        "playresy:",
        "layoutresx:",
        "layoutresy:",
    )

    data class ParsedSubtitleDocument(
        val scriptInfo: AssScriptInfo,
        val styles: List<AssStyle>,
        val events: List<AssDialogueEvent>,
        val preservedSections: Map<String, List<String>> = scriptInfo.preservedSections,
    )

    /**
     * Memeriksa apakah nama file memiliki ekstensi yang didukung (`.ass` atau `.srt`).
     */
    fun isSupportedSubtitleFileName(fileName: String?): Boolean {
        if (fileName.isNullOrBlank()) return false
        val lower = fileName.trim().lowercase()
        return lower.endsWith(".ass") || lower.endsWith(".srt")
    }

    /**
     * Menormalisasi teks mentah berkas subtitle secara aman:
     * - Menghapus UTF-8 BOM (`\uFEFF`)
     * - Menghapus karakter kontrol `\r` (`replace("\r", "")`) dari line-ending Windows
     */
    fun normalizeRawSubtitleText(rawContent: String): String {
        if (rawContent.isEmpty()) return ""
        return rawContent
            .removePrefix("\uFEFF")
            .replace("\uFEFF", "")
            .replace("\r", "")
    }

    /**
     * Mem-parsing isi file `.ass` atau `.srt` menjadi [ParsedSubtitleDocument].
     */
    fun parseSubtitleContent(fileName: String, content: String): ParsedSubtitleDocument {
        val normalized = normalizeRawSubtitleText(content)
        val isSrt = fileName.trim().lowercase().endsWith(".srt") ||
            (!normalized.contains("[Events]", ignoreCase = true) && normalized.contains("-->"))
        return if (isSrt) {
            parseSrt(normalized)
        } else {
            parseAss(normalized)
        }
    }

    fun parseAss(assContent: String): ParsedSubtitleDocument {
        val normalized = normalizeRawSubtitleText(assContent)
        var title = "SubEdit Project"
        var playResX = 1920
        var playResY = 1080
        var layoutResX = 0
        var layoutResY = 0
        var ycbcrMatrix = "None"
        var wrapStyle = 0
        var scaledBorderAndShadow = true
        val extraScriptInfoLines = ArrayList<String>()
        val preservedSections = LinkedHashMap<String, MutableList<String>>()
        val parsedStyles = ArrayList<AssStyle>()
        val rawEvents = ArrayList<AssDialogueEvent>(256)
        var nextId = 1

        var currentSectionHeader = ""
        var currentSectionLower = ""

        normalized.lineSequence().forEach { rawLine ->
            val trimmed = rawLine.trim()
            if (trimmed.isEmpty()) return@forEach

            // Deteksi pergantian section [Section Name]
            if (trimmed.startsWith('[') && trimmed.endsWith(']')) {
                currentSectionHeader = trimmed
                currentSectionLower = trimmed.lowercase()
                if (currentSectionLower != "[script info]" &&
                    currentSectionLower != "[v4+ styles]" &&
                    currentSectionLower != "[v4 styles]" &&
                    currentSectionLower != "[events]"
                ) {
                    preservedSections.getOrPut(currentSectionHeader) { ArrayList() }
                }
                return@forEach
            }

            // Simpan utuh section metadata Aegisub Desktop ([Aegisub Project Garbage], [Aegisub Extradata], [Fonts], [Graphics], dll.)
            if (currentSectionLower.isNotEmpty() &&
                currentSectionLower != "[script info]" &&
                currentSectionLower != "[v4+ styles]" &&
                currentSectionLower != "[v4 styles]" &&
                currentSectionLower != "[events]"
            ) {
                preservedSections.getOrPut(currentSectionHeader) { ArrayList() }.add(rawLine)
                return@forEach
            }

            if (trimmed.startsWith(';')) {
                if (currentSectionLower == "[script info]" &&
                    !trimmed.startsWith("; Script generated by SubEdit", ignoreCase = true)
                ) {
                    extraScriptInfoLines.add(rawLine)
                }
                return@forEach
            }

            when {
                currentSectionLower == "[script info]" || currentSectionLower.isEmpty() -> {
                    when {
                        trimmed.startsWith("Title:", ignoreCase = true) -> {
                            title = trimmed.substringAfter(':').trim().ifEmpty { "SubEdit Project" }
                        }
                        trimmed.startsWith("PlayResX:", ignoreCase = true) -> {
                            val parsed = trimmed.substringAfter(':').trim().toIntOrNull()
                            playResX = if (parsed != null && parsed > 0) parsed.coerceIn(64, 7680) else 1920
                        }
                        trimmed.startsWith("PlayResY:", ignoreCase = true) -> {
                            val parsed = trimmed.substringAfter(':').trim().toIntOrNull()
                            playResY = if (parsed != null && parsed > 0) parsed.coerceIn(64, 4320) else 1080
                        }
                        trimmed.startsWith("LayoutResX:", ignoreCase = true) -> {
                            layoutResX = trimmed.substringAfter(':').trim().toIntOrNull()?.coerceAtLeast(0) ?: 0
                        }
                        trimmed.startsWith("LayoutResY:", ignoreCase = true) -> {
                            layoutResY = trimmed.substringAfter(':').trim().toIntOrNull()?.coerceAtLeast(0) ?: 0
                        }
                        trimmed.startsWith("YCbCr Matrix:", ignoreCase = true) -> {
                            ycbcrMatrix = trimmed.substringAfter(':').trim().ifEmpty { "None" }
                        }
                        trimmed.startsWith("WrapStyle:", ignoreCase = true) -> {
                            wrapStyle = trimmed.substringAfter(':').trim().toIntOrNull()?.coerceIn(0, 3) ?: 0
                        }
                        trimmed.startsWith("ScaledBorderAndShadow:", ignoreCase = true) -> {
                            val v = trimmed.substringAfter(':').trim().lowercase()
                            scaledBorderAndShadow = v != "no" && v != "0" && v != "false"
                        }
                        trimmed.startsWith("Style:", ignoreCase = true) -> {
                            val body = trimmed.substringAfter(':').trim()
                            parseAssStyleLine(body)?.let { parsedStyle ->
                                val existingIdx = parsedStyles.indexOfFirst { it.name == parsedStyle.name }
                                if (existingIdx != -1) {
                                    parsedStyles[existingIdx] = parsedStyle
                                } else {
                                    parsedStyles.add(parsedStyle)
                                }
                            }
                        }
                        trimmed.startsWith("Dialogue:", ignoreCase = true) ||
                            trimmed.startsWith("Comment:", ignoreCase = true) -> {
                            parseAssEventLine(trimmed, nextId)?.let { ev ->
                                rawEvents.add(ev)
                                nextId++
                            }
                        }
                        else -> {
                            val lowerLine = trimmed.lowercase()
                            if (KNOWN_SCRIPT_INFO_PREFIXES.none { lowerLine.startsWith(it) }) {
                                extraScriptInfoLines.add(rawLine)
                            }
                        }
                    }
                }
                currentSectionLower == "[v4+ styles]" || currentSectionLower == "[v4 styles]" -> {
                    if (trimmed.startsWith("Style:", ignoreCase = true)) {
                        val body = trimmed.substringAfter(':').trim()
                        parseAssStyleLine(body)?.let { parsedStyle ->
                            val existingIdx = parsedStyles.indexOfFirst { it.name == parsedStyle.name }
                            if (existingIdx != -1) {
                                parsedStyles[existingIdx] = parsedStyle
                            } else {
                                parsedStyles.add(parsedStyle)
                            }
                        }
                    }
                }
                currentSectionLower == "[events]" -> {
                    if (trimmed.startsWith("Dialogue:", ignoreCase = true) ||
                        trimmed.startsWith("Comment:", ignoreCase = true)
                    ) {
                        parseAssEventLine(trimmed, nextId)?.let { ev ->
                            rawEvents.add(ev)
                            nextId++
                        }
                    }
                }
            }
        }

        // Pertahankan 100% seluruh style asli dari [V4+ Styles]; hanya gunakan Default jika [V4+ Styles] benar-benar kosong
        val finalStyles = if (parsedStyles.isEmpty()) {
            AssStyle.defaultSingleStyle()
        } else {
            parsedStyles
        }

        val immutablePreserved = preservedSections.mapValues { it.value.toList() }
        val scriptInfo = AssScriptInfo(
            title = title,
            playResX = playResX,
            playResY = playResY,
            layoutResX = layoutResX,
            layoutResY = layoutResY,
            ycbcrMatrix = ycbcrMatrix,
            wrapStyle = wrapStyle,
            scaledBorderAndShadow = scaledBorderAndShadow,
            extraScriptInfoLines = extraScriptInfoLines,
            preservedSections = immutablePreserved,
        )

        return ParsedSubtitleDocument(
            scriptInfo = scriptInfo,
            styles = finalStyles,
            events = rawEvents,
            preservedSections = immutablePreserved,
        )
    }

    private fun parseAssEventLine(line: String, id: Int): AssDialogueEvent? {
        val isComment = line.startsWith("Comment:", ignoreCase = true)
        val body = line.substringAfter(':').trimStart()
        val parts = body.split(',', limit = 10)
        // Validasi 10 kolom standar ASS v4+: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
        if (parts.size < 10) return null

        val layerPart = parts[0].trim()
        val layer = layerPart.substringAfter('=').toIntOrNull() ?: 0
        val startUs = SubTime.parseAssOrNull(parts[1].trim()) ?: return null
        val parsedEndUs = SubTime.parseAssOrNull(parts[2].trim()) ?: return null
        val validEndUs = if (parsedEndUs >= startUs) parsedEndUs else startUs
        // Pertahankan 100% nama style asli (misal DefaultCR, DefaultCR Italics, DefaultCR Tops)
        val rawStyleName = parts[3].trim().removePrefix("*").ifEmpty { "Default" }
        val actor = parts[4].trim()
        val marginL = parts[5].trim().toIntOrNull()?.coerceAtLeast(0) ?: 0
        val marginR = parts[6].trim().toIntOrNull()?.coerceAtLeast(0) ?: 0
        val marginV = parts[7].trim().toIntOrNull()?.coerceAtLeast(0) ?: 0
        val effect = parts[8].trim()
        val text = parts[9]

        return AssDialogueEvent(
            id = id,
            layer = layer,
            startUs = startUs.coerceAtLeast(0L),
            endUs = validEndUs.coerceAtLeast(startUs),
            isComment = isComment,
            style = rawStyleName,
            actor = actor,
            marginL = marginL,
            marginR = marginR,
            marginV = marginV,
            effect = effect,
            rawText = text,
        )
    }

    /**
     * Mem-parsing file SubRip (`.srt`) dan mengonversi newline menjadi `\N` ASS.
     */
    fun parseSrt(srtContent: String): ParsedSubtitleDocument {
        val normalized = normalizeRawSubtitleText(srtContent).trim()
        if (normalized.isEmpty()) {
            return ParsedSubtitleDocument(
                scriptInfo = AssScriptInfo(),
                styles = AssStyle.defaultSingleStyle(),
                events = emptyList(),
            )
        }

        val blocks = normalized.split(Regex("""\n\s*\n"""))
        val events = ArrayList<AssDialogueEvent>(blocks.size)
        val htmlTagRegex = Regex("""</?[^>]+>""")
        var nextId = 1

        for (block in blocks) {
            val lines = block.lines().map { it.trim() }.filter { it.isNotEmpty() }
            if (lines.isEmpty()) continue

            val timeLineIndex = lines.indexOfFirst { "-->" in it }
            if (timeLineIndex == -1 || timeLineIndex >= lines.lastIndex) continue

            val timeParts = lines[timeLineIndex].split("-->")
            if (timeParts.size < 2) continue

            val startUs = SubTime.parseAssOrNull(timeParts[0].trim()) ?: continue
            val endUs = SubTime.parseAssOrNull(timeParts[1].trim().substringBefore(' '))
                ?: (startUs + 2_000_000L)

            val textLines = lines.subList(timeLineIndex + 1, lines.size)
            val assText = textLines.joinToString("\\N") { line ->
                line
                    .replace("<i>", "{\\i1}", ignoreCase = true)
                    .replace("</i>", "{\\i0}", ignoreCase = true)
                    .replace("<b>", "{\\b1}", ignoreCase = true)
                    .replace("</b>", "{\\b0}", ignoreCase = true)
                    .replace("<u>", "{\\u1}", ignoreCase = true)
                    .replace("</u>", "{\\u0}", ignoreCase = true)
                    .replace(htmlTagRegex, "")
            }

            events.add(
                AssDialogueEvent(
                    id = nextId++,
                    startUs = startUs,
                    endUs = endUs.coerceAtLeast(startUs + 100_000L),
                    isComment = false,
                    style = "Default",
                    actor = "",
                    effect = "",
                    rawText = assText,
                )
            )
        }

        return ParsedSubtitleDocument(
            scriptInfo = AssScriptInfo(title = "SRT Imported Project"),
            styles = AssStyle.defaultSingleStyle(),
            events = events,
        )
    }

    /**
     * Mem-parsing seluruh 23 kolom definisi `Style:` di `[V4+ Styles]`.
     */
    private fun parseAssStyleLine(rawBody: String): AssStyle? {
        val parts = rawBody.split(',').map { it.trim() }
        if (parts.size < 22) return null

        return AssStyle(
            name = parts[0].ifEmpty { "Default" },
            fontname = parts[1].ifEmpty { "Trebuchet MS" },
            fontsize = (parts[2].toFloatOrNull() ?: 48f).coerceIn(1f, 500f),
            primaryColorHex = AssColorConverter.assToHex(parts[3], "#FFFFFF"),
            secondaryColorHex = AssColorConverter.assToHex(parts[4], "#0000FF"),
            outlineColorHex = AssColorConverter.assToHex(parts[5], "#000000"),
            shadowColorHex = AssColorConverter.assToHex(parts[6], "#000000"),
            primaryAlphaHex = AssColorConverter.assToAlphaHex(parts[3], "00"),
            secondaryAlphaHex = AssColorConverter.assToAlphaHex(parts[4], "00"),
            outlineAlphaHex = AssColorConverter.assToAlphaHex(parts[5], "00"),
            shadowAlphaHex = AssColorConverter.assToAlphaHex(parts[6], "00"),
            bold = parts[7] == "-1" || parts[7] == "1",
            italic = parts[8] == "-1" || parts[8] == "1",
            underline = parts[9] == "-1" || parts[9] == "1",
            strikeout = parts[10] == "-1" || parts[10] == "1",
            scaleX = parts[11].toFloatOrNull() ?: 100f,
            scaleY = parts[12].toFloatOrNull() ?: 100f,
            spacing = parts[13].toFloatOrNull() ?: 0f,
            angle = parts[14].toFloatOrNull() ?: 0f,
            borderStyle = parts[15].toIntOrNull() ?: 1,
            outline = (parts[16].toFloatOrNull() ?: 2.5f).coerceAtLeast(0f),
            shadow = (parts[17].toFloatOrNull() ?: 1.5f).coerceAtLeast(0f),
            alignment = (parts[18].toIntOrNull() ?: 2).coerceIn(1, 9),
            marginL = (parts[19].toIntOrNull() ?: 60).coerceAtLeast(0),
            marginR = (parts[20].toIntOrNull() ?: 60).coerceAtLeast(0),
            marginV = (parts[21].toIntOrNull() ?: 45).coerceAtLeast(0),
            encoding = parts.getOrNull(22)?.toIntOrNull() ?: 1,
        )
    }

    private fun formatAssNumber(value: Float): String {
        return if (value % 1f == 0f) value.toInt().toString() else value.toString()
    }

    /**
     * Men-serialisasi seluruh 23 kolom `[V4+ Styles]` kembali ke format standar ASS v4+.
     */
    fun serializeAssStyleLine(s: AssStyle): String {
        val c1 = AssColorConverter.hexToAss(s.primaryColorHex, s.primaryAlphaHex)
        val c2 = AssColorConverter.hexToAss(s.secondaryColorHex, s.secondaryAlphaHex)
        val c3 = AssColorConverter.hexToAss(s.outlineColorHex, s.outlineAlphaHex)
        val c4 = AssColorConverter.hexToAss(s.shadowColorHex, s.shadowAlphaHex)
        val b = if (s.bold) -1 else 0
        val i = if (s.italic) -1 else 0
        val u = if (s.underline) -1 else 0
        val st = if (s.strikeout) -1 else 0
        val fs = formatAssNumber(s.fontsize)
        val scX = formatAssNumber(s.scaleX)
        val scY = formatAssNumber(s.scaleY)
        val sp = formatAssNumber(s.spacing)
        val ang = formatAssNumber(s.angle)
        val outl = formatAssNumber(s.outline)
        val shad = formatAssNumber(s.shadow)
        return "Style: ${s.name},${s.fontname},$fs,$c1,$c2,$c3,$c4,$b,$i,$u,$st,$scX,$scY,$sp,$ang,${s.borderStyle},$outl,$shad,${s.alignment},${s.marginL},${s.marginR},${s.marginV},${s.encoding}"
    }

    /**
     * Mengekspor state skrip aktif menjadi isi file `.ass` standar Aegisub Desktop secara utuh
     * (termasuk `[Script Info]`, `[Aegisub Project Garbage]`, 23 kolom `[V4+ Styles]`,
     * `[Fonts]`, `[Graphics]`, `[Events]` beserta `Comment:`, dan `[Aegisub Extradata]`).
     */
    fun exportToAss(
        scriptInfo: AssScriptInfo,
        styles: List<AssStyle>,
        events: List<AssDialogueEvent>,
        preservedSections: Map<String, List<String>> = scriptInfo.preservedSections,
    ): String = buildString(8192) {
        appendLine("[Script Info]")
        appendLine("; Script generated by SubEdit Mobile ASS Subtitle Editor")
        appendLine("Title: ${scriptInfo.title}")
        appendLine("ScriptType: v4.00+")
        appendLine("WrapStyle: ${scriptInfo.wrapStyle}")
        appendLine("ScaledBorderAndShadow: ${if (scriptInfo.scaledBorderAndShadow) "yes" else "no"}")
        appendLine("YCbCr Matrix: ${scriptInfo.ycbcrMatrix.ifBlank { "None" }}")
        appendLine("PlayResX: ${scriptInfo.playResX}")
        appendLine("PlayResY: ${scriptInfo.playResY}")
        if (scriptInfo.layoutResX > 0 && scriptInfo.layoutResY > 0) {
            appendLine("LayoutResX: ${scriptInfo.layoutResX}")
            appendLine("LayoutResY: ${scriptInfo.layoutResY}")
        }
        for (extraLine in scriptInfo.extraScriptInfoLines) {
            appendLine(extraLine)
        }
        appendLine()

        // Tulis [Aegisub Project Garbage] jika ada
        val writtenSections = HashSet<String>()
        for ((header, lines) in preservedSections) {
            if (header.equals("[Aegisub Project Garbage]", ignoreCase = true) && lines.isNotEmpty()) {
                appendLine(header)
                for (l in lines) appendLine(l)
                appendLine()
                writtenSections.add(header.lowercase())
            }
        }

        appendLine("[V4+ Styles]")
        appendLine("Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding")
        val activeStyles = styles.ifEmpty { AssStyle.defaultSingleStyle() }
        for (style in activeStyles) {
            appendLine(serializeAssStyleLine(style))
        }
        appendLine()

        // Tulis [Fonts] dan [Graphics] jika ada sebelum [Events]
        for ((header, lines) in preservedSections) {
            val lower = header.lowercase()
            if ((lower == "[fonts]" || lower == "[graphics]") && lines.isNotEmpty() && writtenSections.add(lower)) {
                appendLine(header)
                for (l in lines) appendLine(l)
                appendLine()
            }
        }

        appendLine("[Events]")
        appendLine("Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text")
        for (ev in events) {
            val prefix = if (ev.isComment) "Comment" else "Dialogue"
            append(prefix).append(": ")
            append(ev.layer).append(',')
            append(SubTime.formatAss(ev.startUs)).append(',')
            append(SubTime.formatAss(ev.endUs)).append(',')
            append(ev.style).append(',')
            append(ev.actor).append(',')
            append(ev.marginL).append(',')
            append(ev.marginR).append(',')
            append(ev.marginV).append(',')
            append(ev.effect).append(',')
            appendLine(ev.rawText)
        }

        // Tulis [Aegisub Extradata] dan section kustom lainnya di akhir berkas
        for ((header, lines) in preservedSections) {
            val lower = header.lowercase()
            if (lines.isNotEmpty() && writtenSections.add(lower)) {
                appendLine()
                appendLine(header)
                for (l in lines) appendLine(l)
            }
        }
    }
}
